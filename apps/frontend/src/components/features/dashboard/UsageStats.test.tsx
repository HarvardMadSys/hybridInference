// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { UsageStats } from './UsageStats';

vi.mock('@/lib/hooks', () => ({
  useUsageStats: vi.fn(),
}));

import { useUsageStats } from '@/lib/hooks';

const mockedUseUsageStats = useUsageStats as unknown as ReturnType<typeof vi.fn>;

afterEach(() => {
  cleanup();
});

/** The figure shown beside a secondary label such as "Cache reads". */
function detail(label: string): string | null | undefined {
  return screen.getByText(label).nextElementSibling?.textContent;
}

const baseStats = {
  period: 'today' as const,
  quota: {
    has_key: true,
    daily_limit_usd: 10,
    spent_today_usd: 0,
    remaining_today_usd: 10,
    reset_at: new Date('2030-01-01T00:00:00Z').toISOString(),
    reset_timezone: 'UTC',
    contact_email: 'admin@example.com',
  },
  usage: { requests: 0, prompt_tokens: 0, completion_tokens: 0, cost_usd: 0 },
};

describe('UsageStats max_concurrency', () => {
  it('renders the concurrency line when max_concurrency is set', () => {
    mockedUseUsageStats.mockReturnValue({
      data: { ...baseStats, quota: { ...baseStats.quota, max_concurrency: 5 } },
      isLoading: false,
      error: null,
    });
    render(<UsageStats />);
    expect(screen.getByText(/Max concurrent requests:\s*5/)).toBeInTheDocument();
  });

  it('renders "Unlimited" when max_concurrency is 0', () => {
    mockedUseUsageStats.mockReturnValue({
      data: { ...baseStats, quota: { ...baseStats.quota, max_concurrency: 0 } },
      isLoading: false,
      error: null,
    });
    render(<UsageStats />);
    expect(screen.getByText(/Max concurrent requests:\s*Unlimited/)).toBeInTheDocument();
  });

  it('hides the concurrency line when max_concurrency is undefined', () => {
    mockedUseUsageStats.mockReturnValue({
      data: baseStats,
      isLoading: false,
      error: null,
    });
    render(<UsageStats />);
    expect(screen.queryByText(/Max concurrent requests:/)).not.toBeInTheDocument();
  });
});

describe('UsageStats help', () => {
  it('says Today and This Month start at 00:00 UTC, as the quota does', () => {
    mockedUseUsageStats.mockReturnValue({ data: baseStats, isLoading: false, error: null });
    render(<UsageStats />);
    fireEvent.click(screen.getByRole('button', { name: 'About Estimated cost' }));
    expect(
      screen.getByText(/Today and This Month start at 00:00 UTC, when the daily quota resets/),
    ).toBeInTheDocument();
    expect(screen.queryByText(/follows your timezone/)).not.toBeInTheDocument();
  });

  it('opens on a press rather than only on hover, and closes on Escape', () => {
    mockedUseUsageStats.mockReturnValue({ data: baseStats, isLoading: false, error: null });
    render(<UsageStats />);
    const button = screen.getByRole('button', { name: 'About Output Tokens' });
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument();
    expect(button).toHaveAttribute('aria-expanded', 'false');

    fireEvent.click(button);
    const tip = screen.getByRole('tooltip');
    expect(tip).toHaveTextContent(/may already be counted in Output Tokens/);
    expect(button).toHaveAttribute('aria-expanded', 'true');
    expect(button).toHaveAccessibleDescription(/Tokens generated by the model/);

    fireEvent.keyDown(document, { key: 'Escape' });
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument();
    expect(button).toHaveAttribute('aria-expanded', 'false');
  });
});

describe('UsageStats cache and reasoning tokens', () => {
  it('shows cache reads with their share of input, and reasoning tokens', () => {
    mockedUseUsageStats.mockReturnValue({
      data: {
        ...baseStats,
        usage: {
          ...baseStats.usage,
          prompt_tokens: 2000,
          completion_tokens: 300,
          cache_read_tokens: 500,
          cache_write_tokens: 120,
          reasoning_tokens: 80,
        },
      },
      isLoading: false,
      error: null,
    });
    render(<UsageStats />);
    expect(detail('Cache reads')).toBe('500 · 25%');
    expect(detail('Cache writes')).toBe('120');
    // Reasoning is a count of its own, never a share of output tokens.
    expect(detail('Reasoning tokens')).toBe('80');
  });

  it('hides cache writes when none were reported and treats missing fields as zero', () => {
    // An older backend omits the new fields entirely.
    mockedUseUsageStats.mockReturnValue({ data: baseStats, isLoading: false, error: null });
    render(<UsageStats />);
    expect(detail('Cache reads')).toBe('0 · 0%');
    expect(screen.queryByText('Cache writes')).not.toBeInTheDocument();
    expect(detail('Reasoning tokens')).toBe('0');
  });

  it('caps the cache share at 100% when a provider over-reports cache reads', () => {
    mockedUseUsageStats.mockReturnValue({
      data: {
        ...baseStats,
        usage: { ...baseStats.usage, prompt_tokens: 100, cache_read_tokens: 150 },
      },
      isLoading: false,
      error: null,
    });
    render(<UsageStats />);
    expect(detail('Cache reads')).toBe('150 · 100%');
  });
});
